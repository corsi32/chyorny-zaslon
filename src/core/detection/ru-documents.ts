/*
 * Российские документы и реквизиты: СНИЛС, паспорт РФ, номер банковского
 * счёта, а также проверка номера карты по префиксу платёжной системы.
 *
 * Принцип общий: шаблон находит кандидата по форме записи, а валидатор
 * отсекает случайные числа (контрольное число, допустимый год, префикс).
 */

/*
 * Границы — только по цифрам. Буквы вплотную допускаются: при вставке текста
 * без переносов строк к номеру прилипает начало следующей строки
 * («СНИЛС: 123-456-789 64Адрес регистрации…»), и запрет на соседние буквы
 * пропускал такие номера без маски. Цифры вплотную по-прежнему запрещены —
 * иначе номер выдёргивался бы из длинного числа.
 */
const LEFT = String.raw`(?<!\p{N})`;
const RIGHT = String.raw`(?!\p{N})`;

function digitsOf(value: string): string {
  return value.replace(/\D/g, '');
}

// ------------------------------------------------------------------ СНИЛС ---

/**
 * Контрольное число СНИЛС. Первые 9 цифр умножаются на веса 9, 8, …, 1 и
 * складываются. Сумма < 100 — это и есть контрольное число; 100 и 101 дают
 * «00»; больше 101 — остаток от деления на 101 (и снова 100 → «00»).
 * Проверка определена только для номеров больше 001-001-998 — меньшие
 * не принимаем, чтобы не ловить случайные «000-000-000 00».
 */
export function snilsValid(value: string): boolean {
  const d = digitsOf(value);
  if (d.length !== 11) return false;
  if (Number(d.slice(0, 9)) <= 1001998) return false;
  let sum = 0;
  for (let i = 0; i < 9; i++) sum += (d.charCodeAt(i) - 48) * (9 - i);
  let control = sum;
  if (sum >= 100) control = sum % 101 === 100 ? 0 : sum % 101;
  return control === Number(d.slice(9));
}

/**
 * «СНИЛС» перед числом (до 20 символов без цифр между ними). Проверка назад
 * дорогая, поэтому в шаблоне перед ней стоит (?=\d): она выполняется только
 * там, где начинается число, а не в каждой позиции текста.
 */
const SNILS_CONTEXT = String.raw`(?<=[Сс][Нн][Ии][Лл][Сс][^\p{N}\n]{0,20})`;

export function snilsPattern(): RegExp {
  return new RegExp(
    [
      // 123-456-789 01, 123-456-789-01, 123 456 789 01 — форма уже говорит сама за себя.
      String.raw`${LEFT}\d{3}([- ])\d{3}\1\d{3}[- ]\d{2}${RIGHT}`,
      // 12345678901 — 11 цифр подряд только после слова «СНИЛС».
      String.raw`(?=\d)${SNILS_CONTEXT}${LEFT}\d{11}${RIGHT}`,
    ].join('|'),
    'gu',
  );
}

// ---------------------------------------------------------------- Паспорт ---

/**
 * Серия паспорта РФ — 4 цифры: две первые — код региона, две последние — год
 * изготовления бланка. Бланки нового образца выпускаются с 1997 года, поэтому
 * год должен быть 97–99 или 00…(текущий год + 1). Номер — 6 цифр.
 * Контрольной суммы у паспорта нет, поэтому без слова «паспорт»/«серия»
 * принимается только каноническая запись «45 12 123456».
 */
export function passportValid(value: string, now: Date = new Date()): boolean {
  const d = digitsOf(value);
  if (d.length !== 10) return false;
  const year = Number(d.slice(2, 4));
  const maxYear = (now.getFullYear() + 1) % 100;
  return year >= 97 || year <= maxYear;
}

/**
 * Слово-подсказка должно быть целым словом: «серийник SN4512123456» — не
 * паспорт, хотя начинается на «сер». Сокращение «сер.» — только с точкой.
 */
const PASSPORT_CONTEXT = String.raw`(?<=(?<!\p{L})(?:[Пп]аспорт\p{L}*|[Сс]ерия|[Сс]ерии|[Сс]ер\.)(?!\p{L})[^\p{N}\n]{0,25})`;

export function passportPattern(): RegExp {
  return new RegExp(
    [
      // После «паспорт», «серия»: 4512 123456, 45 12 123456, 4512123456, 4512 № 123456,
      // 4512 номер 123456, «серия 4512, номер 123456» (запятая — только перед № / «номер»).
      String.raw`(?=\d)${PASSPORT_CONTEXT}${LEFT}\d{2} ?\d{2}(?:[ \t]*,?[ \t]*(?:№|N|номер|ном\.)[ \t]*|[ \t]*)\d{6}${RIGHT}`,
      // Без контекста — только «45 12 123456».
      String.raw`${LEFT}\d{2} \d{2} \d{6}${RIGHT}`,
    ].join('|'),
    'gu',
  );
}

// ------------------------------------------------------- Банковский счёт ---

/**
 * Номер счёта в банке РФ — 20 цифр: первые 5 — балансовый счёт, 6–8 — код
 * валюты (810 — рубль в нумерации счетов, 840 — доллар США, 978 — евро и т.д.).
 * Контрольную цифру без БИК не проверить, поэтому решение принимается так:
 *  - есть слово «р/с», «счёт», «л/с» перед номером — принимаем любой счёт,
 *    кроме корреспондентского (30101…, это реквизит банка, а не человека);
 *  - слова нет — принимаем только счета физических лиц и ИП с известным
 *    кодом валюты: 40817, 40820 (физлица), 40802 (ИП), 423xx, 426xx (вклады).
 */
const ACCOUNT_CURRENCIES = new Set(['810', '643', '840', '978', '156', '826', '756', '398', '933']);
const PERSONAL_ACCOUNT_PREFIXES = ['40817', '40820', '40802', '423', '426'];

export function bankAccountValid(value: string, hasContext: boolean): boolean {
  const d = digitsOf(value);
  if (d.length !== 20) return false;
  if (d.startsWith('301')) return false;
  if (hasContext) return d[0] !== '0';
  return (
    PERSONAL_ACCOUNT_PREFIXES.some((p) => d.startsWith(p)) &&
    ACCOUNT_CURRENCIES.has(d.slice(5, 8))
  );
}

const ACCOUNT_NUMBER = String.raw`${LEFT}(?:\d{20}|\d{5} \d{3} \d \d{4} \d{7}|\d{4}(?: \d{4}){4})${RIGHT}`;
/** Слова-подсказки, которые могут стоять перед номером счёта. */
const ACCOUNT_CONTEXT =
  /(?:[рР]\/?\s?[сС]ч?|[лЛ]\/[сС]|[сС]ч[её]т\p{L}*(?:\s+№)?|[сС]ч\.|account(?:\s+(?:no\.?|number))?)[^\p{N}\n]{0,20}$/u;

/** Поиск счетов: смотрим, есть ли слово-подсказка в 40 символах перед номером. */
export function findBankAccounts(text: string): { index: number; value: string }[] {
  const out: { index: number; value: string }[] = [];
  for (const m of text.matchAll(new RegExp(ACCOUNT_NUMBER, 'gu'))) {
    const index = m.index!;
    const before = text.slice(Math.max(0, index - 40), index);
    if (bankAccountValid(m[0], ACCOUNT_CONTEXT.test(before))) out.push({ index, value: m[0] });
  }
  return out;
}

// -------------------------------------------------------------------- Карты ---

/**
 * Префикс (IIN) и длина номера карты для распространённых платёжных систем.
 * Номер, не принадлежащий ни одной системе, картой не считается — даже если
 * случайно проходит алгоритм Луна (а проходит каждое десятое число).
 */
export function cardScheme(value: string): string | null {
  const d = digitsOf(value);
  const n = d.length;
  const p2 = Number(d.slice(0, 2));
  const p3 = Number(d.slice(0, 3));
  const p4 = Number(d.slice(0, 4));
  if (p4 >= 2200 && p4 <= 2204) return n >= 16 && n <= 19 ? 'mir' : null;
  if (d[0] === '4') return n === 13 || n === 16 || n === 19 ? 'visa' : null;
  if ((p2 >= 51 && p2 <= 55) || (p4 >= 2221 && p4 <= 2720)) return n === 16 ? 'mastercard' : null;
  if (p2 === 34 || p2 === 37) return n === 15 ? 'amex' : null;
  if (p2 === 62) return n >= 16 && n <= 19 ? 'unionpay' : null;
  if (p4 >= 3528 && p4 <= 3589) return n >= 16 && n <= 19 ? 'jcb' : null;
  if (p4 === 6011 || (p3 >= 644 && p3 <= 649) || p2 === 65) {
    return n >= 16 && n <= 19 ? 'discover' : null;
  }
  if (p2 === 36 || (p3 >= 300 && p3 <= 305) || p2 === 38 || p2 === 39) {
    return n >= 14 && n <= 19 ? 'diners' : null;
  }
  if (p2 === 50 || (p2 >= 56 && p2 <= 69)) return n >= 13 && n <= 19 ? 'maestro' : null;
  return null;
}
