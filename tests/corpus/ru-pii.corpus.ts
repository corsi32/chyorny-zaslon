import type { FindingType } from '@/core/detection';

/**
 * Размеченный набор текстов для оценки качества детекторов (точность и полнота).
 *
 * Каждый пример — текст и список значений, которые в нём должны быть найдены.
 * Если значение не указано, его находить нельзя: любая находка сверх списка
 * считается ложным срабатыванием. Учитываются только типы из EVALUATED_TYPES.
 *
 * Все персональные данные вымышлены. Номера СНИЛС, карт и т. п. либо
 * специально подобраны под контрольные суммы, либо намеренно их не проходят.
 * Набор составлен вручную и не исчерпывающий: при обнаружении ошибки в
 * реальном тексте её стоит добавить сюда отдельным примером.
 */

export interface CorpusEntity {
  readonly type: FindingType;
  readonly value: string;
}

export interface CorpusSample {
  /** Откуда взят шаблон текста — для отчёта по категориям. */
  readonly category: 'chat' | 'document' | 'receipt' | 'code' | 'table' | 'prose';
  readonly text: string;
  readonly expected: readonly CorpusEntity[];
}

export const EVALUATED_TYPES: readonly FindingType[] = [
  'phone',
  'address_ru',
  'passport',
  'snils',
  'bank_account',
  'credit_card',
];

const e = (type: FindingType, value: string): CorpusEntity => ({ type, value });

